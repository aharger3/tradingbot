def _slice(rows, all_months, sessions):
    days = {r["day"] for r in rows}
    tot = sum(r["pnl"] for r in rows)
    by_m = collections.defaultdict(float)
    for r in rows:
        by_m[r["day"][:7]] += r["pnl"]
    w = [r["pnl"] for r in rows if r["pnl"] > 0]
    l = [r["pnl"] for r in rows if r["pnl"] < 0]
    return {"trades": len(rows), "days_traded": len(days),
            "per_day": round(tot / sessions),
            "months_green": sum(1 for m in all_months if by_m.get(m, 0.0) > 0),
            "months": len(all_months),
            "win_pct": round(100.0 * len(w) / len(rows), 1) if rows else None,
            "avg_win": round(sum(w) / len(w)) if w else None,
            "avg_loss": round(-sum(l) / len(l)) if l else None}


def causal_figures():
    """The engine-side day policy (day_policy.py, L5) on its own ON book."""
    meta, rows = load_book_any(DAY_POLICY_ON)
    st, git, flags = _stamp_bits(meta)
    if book_stamp.book_id(rows) != st.get("book_id"):
        raise SystemExit("%s: stamp book_id != recomputed" % DAY_POLICY_ON.name)
    core = core11(rows)
    picks = [r for r in core if r.get("status") == "fired" and r.get("traded")]
    sessions = meta.get("sessions")
    all_m = sorted({r["day"][:7] for r in core})
    h1 = [r for r in picks if r["day"] < BOUNDARY]
    h2 = [r for r in picks if r["day"] >= BOUNDARY]
    out = {"identity": {"book_id": st.get("book_id"),
                        "commit": (git.get("commit") or "")[:8],
                        "day_policy": flags.get("signal_runner.DAY_POLICY")},
           "whole": _slice(picks, all_m, sessions),
           "h1": _slice(h1, [m for m in all_m if m < BOUNDARY[:7]], sessions),
           "h2": _slice(h2, [m for m in all_m if m >= BOUNDARY[:7]], sessions)}
    out["whole"]["halted_by_policy"] = sum(1 for r in core if r.get("status") == "day_policy_halt")
    return out


