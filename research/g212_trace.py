    for k in ("sessions", "first", "last", "commit"):
        if hi[k] != pi[k]:
            bad.append("honest vs phantom %s: %r vs %r" % (k, hi[k], pi[k]))
    if (hi["built_at"] or "")[:10] != (pi["built_at"] or "")[:10]:
        bad.append("honest vs phantom built on different days: %s vs %s"
                   % (hi["built_at"], pi["built_at"]))

    # the pinned rebuild reproduces the baseline; the bare HEAD default does not
    rb = got["rebuild"]
    if rb["day_policy_off"]["book_id"] != hi["book_id"]:
        bad.append("book_DAY_POLICY_off (DAY_POLICY=first3) id %s != baseline %s"
                   % (rb["day_policy_off"]["book_id"], hi["book_id"]))
    if rb["bare_head_default"]["book_id"] == hi["book_id"]:
        bad.append("book_DAY_POLICY_on id equals the baseline -- the pin note on the page is stale")

    # figures quoted from committed referee reports (need an exit re-walk this
    # file does not own): the exact string must still be what the report prints
    for rel, needle in QUOTED_FROM_REPORTS:
        p = ROOT / rel
        if not p.exists():
            bad.append("%s missing (page quotes it)" % rel)
        elif needle not in p.read_text(encoding="utf-8"):
            bad.append("%s no longer contains the quoted row: %s" % (rel, needle[:60]))

    # loop.json must point at this book, this unit, this boundary, this id, this pin
    if LOOP_JSON.exists():
        cfg = json.loads(LOOP_JSON.read_text(encoding="utf-8"))
        if Path(cfg.get("baseline_book", "")).name != HONEST.name:
            bad.append("loop.json baseline_book %r is not %s" % (cfg.get("baseline_book"), HONEST.name))
        if cfg.get("unit") != BASELINE_UNIT:
            bad.append("loop.json unit %r is not %s" % (cfg.get("unit"), BASELINE_UNIT))
        if cfg.get("halves_boundary") != BOUNDARY:
            bad.append("loop.json halves_boundary %r != %s" % (cfg.get("halves_boundary"), BOUNDARY))
        if cfg.get("baseline_book_id") != hi["book_id"]:
            bad.append("loop.json baseline_book_id %r != stamped %s"
                       % (cfg.get("baseline_book_id"), hi["book_id"]))
        rebuild = cfg.get("rebuild", {})
        for k, v in REBUILD_ENV_PIN.items():
            if rebuild.get("env", {}).get(k) != v:
                bad.append("loop.json rebuild.env.%s is %r, must be %r -- without the pin the "
                           "OFF arm builds %s, not the baseline"
                           % (k, rebuild.get("env", {}).get(k), v,
                              rb["bare_head_default"]["book_id"]))
        if list(rebuild.get("args", [])) != ["--days", "730"] or rebuild.get("script") != "backtest_2y.py":
            bad.append("loop.json rebuild.script/args drifted: %r %r"
                       % (rebuild.get("script"), rebuild.get("args")))
        uni = cfg.get("universe", {})
        if uni.get("row_filter") != 'tier == "core"':
            bad.append("loop.json universe.row_filter %r != 'tier == \"core\"'" % uni.get("row_filter"))
        bf = cfg.get("baseline_figures", {})
        base = got["honest"]["core11"][BASELINE_UNIT]
        for sl in ("whole", "h1", "h2"):
            for fld in ("per_day", "months_green", "months", "trades"):
                if bf.get(sl, {}).get(fld) != base[sl].get(fld):
                    bad.append("loop.json baseline_figures.%s.%s %r != book %r"
                               % (sl, fld, bf.get(sl, {}).get(fld), base[sl].get(fld)))
    else:
        bad.append("research/tape/loop.json missing")

    if bad:
        print("FAIL -- %d figure(s) on research/g212_baseline_verdict.md no longer trace:" % len(bad))
        for b in bad:
            print("  " + b)
        return 1
    n = sum(1 for _ in _leaves(EXPECTED)) + len(QUOTED_FROM_REPORTS)
    print("PASS -- %d figures on research/g212_baseline_verdict.md trace to %s (id %s), "
          "%s (id %s), the L5 pair, the three ladder books and two committed referee reports"
          % (n, HONEST.name, hi["book_id"], PHANTOM.name, pi["book_id"]))
    return 0


