def publishes_number(md_content: str) -> bool:
    """
    Detect if markdown publishes quantitative findings.

    Signals:
    - Bolded numbers: **+X.XXX**, **X.XXX**, etc (R-multiples, percentages)
    - Tables with numeric results (| col | 123 | +X.XX |)
    - "Run:" or "Generated by" directives pointing to a script
    """

    # 1. Bolded numbers (R-multiples, percentages, win rates, counts)
    #    Examples: **+0.0609**, **76.6%**, **1017**
    if re.search(r'\*\*[+-]?\d+\.?\d*[%R]?\*\*', md_content):
        return True

    # 2. "Run:" or "Generated by" pointing to a script
    if re.search(r'(Run|Generated by):\s*`.*?\.py`', md_content):
        return True

    # 3. Tables that look like results (numeric data with | separators)
    lines = md_content.split('\n')
    table_lines = [l for l in lines if '|' in l]

    # Heuristic: if we have 3+ lines with | that contain numbers,
    # and it looks like a data table (header + separator + rows)
    if len(table_lines) >= 4:  # header, separator, at least 2 data rows
        # Check for pipe-separated numeric content
        numeric_pipes = sum(1 for l in table_lines if re.search(r'\|\s*[+-]?\d+\.?\d*', l))
        if numeric_pipes >= 3:  # At least 3 lines with numbers in columns
            return True

    return False


