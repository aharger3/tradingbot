def main():
    research_dir = Path('research')

    # Find all .md files in research/
    md_files = sorted(research_dir.glob('*.md'))

    # Filter to those that publish numbers
    orphans = []
    for md_path in md_files:
        try:
            with open(md_path, encoding='utf-8', errors='replace') as f:
                content = f.read()
        except (FileNotFoundError, OSError):
            # Skip files we can't read
            continue

        if publishes_number(content):
            if not find_corresponding_script(md_path):
                orphans.append(md_path)

    # Report
    if orphans:
        print(f'FAIL: {len(orphans)} markdown file(s) publish numbers without committed scripts:')
        for path in orphans:
            print(f'  {path}')
        return 1
    else:
        print(f'PASS: All {len(md_files)} research/*.md files are accounted for.')
        return 0


if __name__ == '__main__':
    sys.exit(main())
